WITH FIRST_HALF AS (SELECT FLAVOR, SUM(TOTAL_ORDER) AS TOTAL_ORDER FROM FIRST_HALF GROUP BY FLAVOR),
JULY AS (SELECT FLAVOR, SUM(TOTAL_ORDER) AS TOTAL_ORDER FROM JULY GROUP BY FLAVOR)

SELECT FH.FLAVOR
FROM FIRST_HALF FH
JOIN JULY J ON FH.FLAVOR = J.FLAVOR
ORDER BY FH.TOTAL_ORDER+J.TOTAL_ORDER DESC
LIMIT 3;


